//   חדשות — כותרת עיתונאית חופשית שלא תמיד מכילה מילות מפתח, ויש לה תקציר
//          מהמקור שמוצג בכרטיס → 4 (נשארת בפיד).
const DEFAULT_SCORE = { maya: 3, news: 4 }

export function scoreReport(item, { source = 'maya' } = {}) {
  const text = item.title || ''
  let score = DEFAULT_SCORE[source] ?? 4
  let direction = 'neutral'

  const hit =
    OVERRIDE.find((r) => r.re.test(text)) ??
    (ROUTINE_FORMS.some((re) => re.test(text))
      ? { w: 2, dir: 'neutral' }
      : RULES.find((r) => r.re.test(text)))

  if (hit) {
    score = hit.w
    direction = hit.dir
  }

  // דיווח שמאיה סימנה כ"מיידי/דחוף" מקבל נקודה — אבל רק אם הוא כבר בעל ערך.
  // בלי התנאי הזה טופס שגרתי מסומן-עדיפות היה מטפס מ-3 ל-4 וחוזר לפיד.
  if (item.is_priority && score >= 5) score = Math.min(10, score + 1)

  return { materiality_score: score, direction }
}
